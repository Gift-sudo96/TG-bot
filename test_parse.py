ok = bad = 0
for text, want_time, want_note in CASES:
    dt, note = parse(text, NOW)
    got_time = dt.strftime("%d.%m %H:%M") if dt else None

    if want_time and want_time.endswith("(+1д)"):
        want_time = "20.08 " + want_time.split()[1]
    time_ok = got_time == want_time
    note_ok = want_note is None or note == want_note
    if time_ok and note_ok:
        ok += 1
        print(f"  OK   {text!r}")
    else:
        bad += 1
        print(f"  ПОМИЛКА  {text!r}")
        if not time_ok:
            print(f"         час:  очікував {want_time!r}, отримав {got_time!r}")
        if not note_ok:
            print(f"         опис: очікував {want_note!r}, отримав {note!r}")

print(f"\n{ok} пройшло, {bad} впало  (з {len(CASES)})")
