    ("перевести 2000 грн клієнту", None, None),
    ("завтрашній звіт готовий", None, None),
    ("оплата 5 к", None, None),
    ("Ок", None, None),

    # --- тривалість проти годинника ---
    ("нагадати на 3 дні", "22.08 11:30", "нагадати"),
    ("зустріч о 3", "19.08 15:00", "зустріч"),

    # --- багаторядковий підпис до скріна ---
