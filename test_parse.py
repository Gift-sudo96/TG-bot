    # --- приклади із задачі ---
    ("завтра", "20.08 09:00", ""),
    ("завтра в 12.00", "20.08 12:00", ""),
    ("фіскалізувати оплату в 5к. завтра в 10.00", "20.08 10:00",
     "фіскалізувати оплату в 5к."),
    ("скільки зараз кредитів залишилось?", None, None),
    ("давай продовжимо робити бота", None, None),
    ("давай продовжимо", None, None),

    # --- різне написання того самого ---
    ("Завтра о 12:00", "20.08 12:00", ""),
    ("ЗАВТРА В 12", "20.08 12:00", ""),
    ("завтра о 12 годині", "20.08 12:00", ""),
    ("завтра, 12:00", "20.08 12:00", ""),

    # --- час у різних місцях речення ---
    ("нагадай завтра зателефонувати Олені", "20.08 09:00",
     "нагадай зателефонувати Олені"),
    ("зателефонувати Олені завтра", "20.08 09:00", "зателефонувати Олені"),
    ("о 16:00 перевірити оплату", "19.08 16:00", "перевірити оплату"),
    ("перевірити оплату о 16:00", "19.08 16:00", "перевірити оплату"),

    # --- відносний час ---
    ("передзвонити через 2 години", "19.08 13:30", "передзвонити"),
    ("через 30 хв", "19.08 12:00", ""),
    ("через тиждень", "26.08 11:30", ""),
    ("через місяць продовжити", "18.09 11:30", "продовжити"),
    ("+3д Іван 1500 грн", "22.08 11:30", "Іван 1500 грн"),
    ("30хв", "19.08 12:00", ""),

    # --- дати ---
    ("нагадай 15.09 о 14:30 про підписку", "15.09 14:30", "нагадай про підписку"),
    ("15 вересня", "15.09 09:00", ""),
    ("продовжити підписку 01.01", "01.01 09:00", "продовжити підписку"),
    ("15.09.2027 з роком", "15.09 09:00", "з роком"),

    # --- дні тижня ---
    ("в понеділок о 9", "24.08 09:00", ""),
    ("пт 18:00 звіт", "21.08 18:00", "звіт"),
    ("наступного понеділка планерка", "31.08 09:00", "планерка"),

    # --- частини доби ---
    ("сьогодні о 20:00", "19.08 20:00", ""),
    ("о 7 вечора зателефонувати", "19.08 19:00", "зателефонувати"),
    ("завтра вранці", "20.08 09:00", ""),
    ("опівдні обід з клієнтом", "19.08 12:00", "обід з клієнтом"),

    # --- те, що НЕ має ставати часом ---
