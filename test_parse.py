"""Перевірка розбору часу з тексту. Запуск: venv\\Scripts\\python.exe test_parse.py"""
from datetime import datetime
from zoneinfo import ZoneInfo

from timeparse import parse

TZ = ZoneInfo("Europe/Kyiv")
NOW = datetime(2026, 8, 19, 11, 30, tzinfo=TZ)   # середа, щоб тест був стабільним

# (текст, очікуваний час "дд.мм ГГ:ХХ" або None, очікуваний опис)
