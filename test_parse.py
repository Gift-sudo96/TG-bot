    ("оплата 2 т", None, None),
    ("нагадати про 5к завтра", "20.08 09:00", "нагадати про 5к"),
    ("10.00", "19.08 10:00 (+1д)", ""),
    ("", None, None),

    # --- пастки: часу тут немає, бот має поставити на 9 ранку ---
